-- F1 · AB 分组结束：新用户一律 taste（2026-09-20）
--
-- ## 发生了什么
--
-- 成对比较（`pairwise` 臂）去掉了。用户 2026-09-20 的判断：
-- 「不论多短，用户都无法从两组如此密集的文字中获得有效信息，
--   甚至于现在这个信息还不是用户领域。」
--
-- 他注册的新账号被分到 `pairwise`，登录后**直接进了 6 组对比、没有标签选择**——
-- 那正是分组在起作用，不是 bug。但既然比较这条路要撤掉，分组就没有对照物了。
--
-- ## 这一列的含义变了，不是被废弃
--
-- `f1_arm` 原本是「实验臂」。现在它是「**这行配置是怎么来的**」：
--   · `text`     —— 一段话描述（2026-09-19 退役）
--   · `pairwise` —— 标签 + 6 组成对比较（2026-09-20 退役）
--   · `taste`    —— 标签（现行）
--
-- **已有行一行都不回改**（口径 F10）。那两批人确实走过那两版，
-- 改写它等于篡改 A5 要读的那段历史；而且读数时「这条配置是怎么来的」
-- 是唯一还能把三批人分开的东西。
--
-- ## 为什么不直接删掉这个函数
--
-- 它挂在 `auth.users` 的触发器上（口径 F08：分组在数据库里算，前端不算）。
-- 删函数要连触发器一起改，而触发器还负责建那一行 `style_config`——
-- 动它的风险远大于让这个函数返回一个常量。
--
-- ⚠️ 返回常量之后，「分组是确定性的」这条性质仍然成立（常量当然确定），
-- 但**它不再有分辨力**。别再拿它做 AB 分析：那会得到一个 100% 一臂的结论，
-- 而那个结论看起来完全正常。

create or replace function public.f1_assign_arm(uid uuid)
returns text
language sql
immutable
as $$
  -- 参数保留：签名变了就要动触发器（见上）。**故意不用它。**
  select case when uid is null then 'taste' else 'taste' end;
$$;

