"""追问时怎么讲（口径 F107）。

## 为什么有这一条

开场原来有一块「卡住的时候」（先给结论 / 要推导 / 拆成小步骤……）。2026-10-07 去掉了，
理由是用户的判断：**难点要用户自己指出来，不是我们推断出来的**——指出的方式就是追问。
而追问时能做的只有再讲一遍：换个角度、更浅白、带一个例子。

那一块问的是一个用户答不了的问题；这里把它换成一条**只在追问时生效**的限定语。
同一个会话里有历史（也就是这一轮是追问）才加；单轮问答一个字都不多。

## 措辞的两条约束

- **不写「讲得更详细」。** 与 `paragraph_length` 的判定方向相反，P2/P3 用户上它会推高
  重生成触发率（同 `CONFUSION_NOTE` 那条理由，口径 F58）。所以说「更浅白」，不说「更长」。
- **让模型自己分清是不是没听懂。** 追问也可能是一个新问题（「那核电站呢？」），
  那时照常回答——不能每一轮追问都被改写成「再讲一遍上一段」。

## 为什么进本轮用户消息、不进 system

同 F57：system 按「会话内不变」设计，而「这一轮是不是追问」逐轮不同
（第一轮没有历史、之后都有）。放进 system 会让同一个会话的第一轮与第二轮 system 不同。
"""

from __future__ import annotations

from typing import Any

__all__ = ["FOLLOWUP_NOTE", "followup_prefix"]

#: 一字不改；改它要先改口径表（F107）。
FOLLOWUP_NOTE = (
    "【这是同一会话里的追问】"
    "如果学生是在说上一段没听懂（例如「没懂」「什么意思」「能不能简单点」，或者换个说法又问同一个点），"
    "就换一个角度重讲那一点：说得更浅白，配一个具体例子，不要照搬上一段的表述，也不要把上一段整段重复。"
    "如果学生要求按调整后的讲法重新讲一遍，就按上面的讲法要求把那个问题完整重讲。"
    "如果是一个新问题，照常回答。"
)


def followup_prefix(history: list[dict[str, Any]]) -> str:
    """有历史（这一轮是追问）→ 限定语；没有 → 空串。**唯一的那一行判断。**"""
    return FOLLOWUP_NOTE if history else ""
