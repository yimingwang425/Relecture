"""免责措辞的两个观察项。**判读标准在跑之前写死**（口径 F29）。

拆成两个数，因为它们的预期方向相反：

| | 含义 | 预期 |
| --- | --- | --- |
| **A · 片段表述** | 「根据这段课件」「这份片段提到」——**在遵守 X06**（system 明确告诉模型「你看到的是片段」），是正常行为 | **基本不变，不该归零** |
| **B · 缺口抱怨** | 「counting variant 没展开」「需要额外材料」——新用户看不懂也无从处理 | **归零** |

混在一个正则里得到的数不可判读：降到 4 分不清是消掉了抱怨还是消掉了正常表述。

**这两条在重生成之前就定死并量过基线**，不是看完新数字再决定哪些算抱怨——
那和按结果挑切片是同一条（F27）。
"""

from __future__ import annotations

import re

__all__ = ["A_FRAGMENT", "B_GAP", "classify"]

#: A · 把材料称为「片段 / 这段课件」的正常表述。遵守 X06，不该消失。
A_FRAGMENT = re.compile(
    r"片段|这段课件|这几段|这份课件|以上内容|课件第\s*\d+\s*页"
)

#: B · 断言材料有缺口、需要别处补的抱怨。要消的是这个。
B_GAP = re.compile(
    r"(没有|未|不)(展开|提到|涉及|说明|提供|给出|包含)"
    r"|需要(额外|另外|更多|补充|别的)"
    r"|超出课件|课件之外|另找|再查|没有更多内容"
)


def classify(text: str) -> tuple[int, int]:
    """→ (A 命中次数, B 命中次数)。"""
    return len(A_FRAGMENT.findall(text)), len(B_GAP.findall(text))
